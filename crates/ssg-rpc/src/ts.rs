//! TypeScript emitter — JSON Schema → `.d.ts`.
//!
//! Why hand-rolled? The `json-schema-to-typescript` ecosystem is
//! Node-only; the alternative crate `typescript-type-def` only
//! understands its own native types (no JSON Schema input). We need
//! the smallest possible Rust → TS translation for a tightly-scoped
//! schema vocabulary (the subset emitted by schemars 1.x for plain
//! `#[derive(JsonSchema)]` structs and enums).
//!
//! Supported schema features (sufficient for >95% of RPC payloads):
//!
//! * Primitives: string, number, integer, boolean, null
//! * Arrays (with item type)
//! * Object with `properties` + `required`
//! * `enum` of literal strings
//! * `anyOf` / `oneOf` → TS union
//! * `$ref` → reference into the local `$defs` table
//!
//! Everything else falls through to `unknown` rather than panicking —
//! the user always gets a working `.d.ts`, even if it loses some
//! precision.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use serde_json::Value;

